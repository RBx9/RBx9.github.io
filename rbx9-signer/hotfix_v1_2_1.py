#!/usr/bin/env python3
# RBx9 v1.2.1 crash hotfix. Source base: Feather, GPL-3.0.
# Conservative: preserve all v1.2 UI, fix off-main SwiftUI ObservableObject
# notifications, and avoid retaining half-built source-list state on refresh.
from pathlib import Path
root=Path("feather")
def update(path,old,new):
 p=root/path
 s=p.read_text()
 if s.count(old)!=1:
  raise RuntimeError(f"Expected exactly one {old[:100]!r} in {path} (found {s.count(old)})")
 p.write_text(s.replace(old,new,1))
 print("v1.2.1:",path)
update("Feather.xcconfig","FEATHER_PROJECT_VERSION=1.2.0","FEATHER_PROJECT_VERSION=1.2.1")
# isFinished is a workflow guard, not UI state. @Published fired from a generic
# async executor, which can trigger SwiftUI off-main publisher violations/crashes.
update("Feather/Views/Sources/SourcesViewModel.swift",
       "@Published var isFinished = true",
       "var isFinished = true")
# Avoid a busy indefinite wait if a refresh is requested while another fetch
# is still active; one request retries after the original completes.
update("Feather/Views/Sources/SourcesViewModel.swift",
       """            while !isFinished {
                if Task.isCancelled { return }
                try? await Task.sleep(nanoseconds: 150_000_000)
            }""",
       """            for _ in 0..<150 {
                if Task.isCancelled { return }
                if isFinished { break }
                try? await Task.sleep(nanoseconds: 150_000_000)
            }
            guard isFinished else { return }""")
# Preserve previous parsed sources until replacement data succeeds.
# UI reload is driven by $sources, which is already updated via MainActor.run.
update("Feather/Views/Sources/Apps/SourceAppsView.swift",
       """        .onChange(of: viewModel.isFinished) { newValue in
            if newValue { _load() }
        }
        .onReceive(viewModel.$sources) { _ in
            _load()
        }""",
       """        .onReceive(viewModel.$sources.receive(on: DispatchQueue.main)) { _ in
            _load()
        }""")
# Protect against double taps that initiate two concurrent signing operations.
update("Feather/Views/Signing/SigningView.swift",
       """private func _start(installAfterSigning: Bool? = nil) {
        if installAfterSigning == nil {""",
       """private func _start(installAfterSigning: Bool? = nil) {
        guard !_isSigning else { return }
        if installAfterSigning == nil {""")
# Only call URLs generated by the installer after app payload is ready.
# The "Open in iTunes" alert is a system confirmation, cannot be tapped by RBx9.
# The existing Semi-Local installer used try! during screen construction.
# A transient HTTP server/socket bind error killed RBx9 instead of displaying an error.
update("Feather/Views/Library/Install/InstallPreviewView.swift",
       "self._installer = StateObject(wrappedValue: try! ServerInstaller(app: app, viewModel: viewModel))",
       "self._installer = StateObject(wrappedValue: ServerInstaller(app: app, viewModel: viewModel))")
p = root/"Feather/Backend/Server/ServerInstaller.swift"
s = p.read_text()
old = """\tinit(app: AppInfoPresentable, viewModel: InstallerStatusViewModel) throws {
\t\tself.app = app
\t\tself.viewModel = viewModel
\t\ttry _setup()
\t\ttry _configureRoutes()
\t\ttry _server?.server.start()
\t\t_needsShutdown = true
\t}"""
new = """    private(set) var startupError: Error?

    init(app: AppInfoPresentable, viewModel: InstallerStatusViewModel) {
        self.app = app
        self.viewModel = viewModel
        do {
            try _setup()
            guard _server != nil else { throw URLError(.cannotConnectToHost) }
            try _configureRoutes()
            try _server?.server.start()
            _needsShutdown = true
        } catch {
            startupError = error
            DispatchQueue.main.async {
                viewModel.status = .broken(error)
            }
        }
    }"""
if s.count(old)!=1:
 raise RuntimeError("ServerInstaller initializer changed")
p.write_text(s.replace(old,new))
# Prevent a failed local server from ever sending the user to a dead browser page.
update("Feather/Views/Library/Install/InstallPreviewView.swift",
       """\tprivate func _install() {
\t\tguard isSharing""",
       """    private func _install() {
        if let error = installer.startupError {
            UIAlertController.showAlertWithOk(
                title: "Installation Server",
                message: "Could not start the installer: " + error.localizedDescription
            )
            return
        }
        guard isSharing""")
print("RBx9 safe installer initialization applied")

print("RBx9 v1.2.1 hotfix patch applied")
